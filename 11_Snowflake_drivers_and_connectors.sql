-- Connecting with GIT

CREATE OR REPLACE SECRET MY_GITHUB_SECRET
TYPE=PASSWORD
USERNAME='add your snowflake username'
PASSWORD='add your password';

CREATE OR REPLACE API INTEGRATION GIT_API_INT
API_PROVIDER=GIT_HTTPS_API
API_ALLOWED_PREFIXES=('https://github.com/ykmphukan')
ALLOWED_AUTHENTICATION_SECRETS =(MY_GITHUB_SECRET)
ENABLED=TRUE;

CREATE OR REPLACE GIT REPOSITORY MY_GITHUB_REPO
  API_INTEGRATION = GIT_API_INT
  GIT_CREDENTIALS = MY_GITHUB_SECRET
  ORIGIN = 'https://github.com/ykmphukan/Snowflake-Demo.git';

  ALTER GIT REPOSITORY MY_GITHUB_REPO FETCH;

  LIST @MY_GITHUB_REPO/branches/main/;
  