  TYPE = 'CSV'
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  SKIP_HEADER = 1
  NULL_IF = ('NULL', '')
  EMPTY_FIELD_AS_NULL = TRUE;

CREATE OR REPLACE STAGE SNOW_DATA_LAKE.DATA_PROVIDER.MY_S3_STAGE_PIPE
  URL = 's3://abhinav-phukan-s3-bucket/'
  CREDENTIALS = (AWS_KEY_ID = 'add your key' AWS_SECRET_KEY = 'add your secret key')
  FILE_FORMAT = SNOW_DATA_LAKE.DATA_PROVIDER.MY_CSV_FORMAT_PIPE;

CREATE OR REPLACE PIPE SNOW_DATA_LAKE.DATA_PROVIDER.MY_SNOWPIPE
  AUTO_INGEST = TRUE
  AS
  COPY INTO SNOW_DATA_LAKE.DATA_PROVIDER.RAW_DATA_TABLE
  FROM @SNOW_DATA_LAKE.DATA_PROVIDER.MY_S3_STAGE_PIPE
  PATTERN = '.*RAW_DATA_TABLE.*[.]csv'
  FILE_FORMAT = (FORMAT_NAME = 'SNOW_DATA_LAKE.DATA_PROVIDER.MY_CSV_FORMAT_PIPE')
  ON_ERROR = 'CONTINUE';

  SELECT * FROM SNOW_DATA_LAKE.DATA_PROVIDER.RAW_DATA_TABLE ;

  LIST @SNOW_DATA_LAKE.DATA_PROVIDER.MY_S3_STAGE_PIPE;

ALTER PIPE SNOW_DATA_LAKE.DATA_PROVIDER.MY_SNOWPIPE REFRESH;

