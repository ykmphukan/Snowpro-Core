USE ROLE SYSADMIN;

CREATE DATABASE PROJECT_DB;
CREATE SCHEMA PROJECT_DB.DEV_STAGING;
CREATE SCHEMA PROJECT_DB.QA_TESTING;
CREATE SCHEMA PROJECT_DB.ANALYTICS;

CREATE WAREHOUSE IF NOT EXISTS DEV_WH
WAREHOUSE_SIZE = 'SMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE;

CREATE WAREHOUSE IF NOT EXISTS QA_WH
WAREHOUSE_SIZE = 'XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE;

CREATE WAREHOUSE IF NOT EXISTS ANALYTICS_WH
WAREHOUSE_SIZE = 'SMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE;

-- ROLES (RBAC)

CREATE ROLE IF NOT EXISTS DEV_ROLE;
CREATE ROLE IF NOT EXISTS QA_ROLE;
CREATE ROLE IF NOT EXISTS BA_ROLE;   
CREATE ROLE IF NOT EXISTS PM_ROLE;   

GRANT ROLE DEV_ROLE TO ROLE PM_ROLE;
GRANT ROLE QA_ROLE TO ROLE PM_ROLE;
GRANT ROLE BA_ROLE TO ROLE PM_ROLE;

GRANT ROLE PM_ROLE TO ROLE SYSADMIN;

-- DAC

GRANT USAGE ON DATABASE PROJECT_DB TO ROLE DEV_ROLE;
GRANT USAGE ON DATABASE PROJECT_DB TO ROLE QA_ROLE;
GRANT USAGE ON DATABASE PROJECT_DB TO ROLE BA_ROLE;

-- FULL CONTROL TO DEV TEAM

GRANT ALL PRIVILEGES ON SCHEMA PROJECT_DB.DEV_STAGING TO ROLE DEV_ROLE;
GRANT USAGE ON WAREHOUSE DEV_WH TO ROLE DEV_ROLE;

-- QA TEAM READ PRIVEILEGES
GRANT USAGE ON SCHEMA PROJECT_DB.DEV_STAGING TO ROLE QA_ROLE;

GRANT ALL PRIVILEGES ON SCHEMA PROJECT_DB.QA_TESTING TO ROLE QA_ROLE;
GRANT USAGE ON WAREHOUSE QA_WH TO ROLE QA_ROLE;

-- BA TEAM 
GRANT USAGE ON SCHEMA PROJECT_DB.ANALYTICS TO ROLE BA_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA PROJECT_DB.ANALYTICS TO ROLE BA_ROLE;

-- FUTURE GRANTS

GRANT SELECT ON FUTURE TABLES IN SCHEMA PROJECT_DB.ANALYTICS TO ROLE BA_ROLE;

