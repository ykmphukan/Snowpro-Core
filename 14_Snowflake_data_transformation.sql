-- JSON

CREATE OR REPLACE FILE FORMAT MY_JSON_FORMAT
  TYPE = 'JSON'
  COMPRESSION = 'AUTO'
  STRIP_OUTER_ARRAY = TRUE;

CREATE OR REPLACE STAGE MY_JSON_STAGE;

LIST @MY_JSON_STAGE;

CREATE OR REPLACE TABLE RAW_JSON_DATA (
    JSON_CONTENT VARIANT
);

COPY INTO RAW_JSON_DATA
FROM @my_json_stage/flowers.json
FILE_FORMAT = (FORMAT_NAME = 'MY_JSON_FORMAT')
ON_ERROR = 'CONTINUE';

SELECT * FROM RAW_JSON_DATA;

CREATE OR REPLACE TABLE FLOWERS (
    CATEGORY STRING,
    INSTRUCTIONS STRING,
    NAME STRING,
    PHOTO STRING,
    PRICE FLOAT,
    PRODUCTID STRING
);

INSERT INTO FLOWERS (CATEGORY, INSTRUCTIONS, NAME, PHOTO, PRICE, PRODUCTID)
SELECT
    JSON_CONTENT:"category"::STRING,
    JSON_CONTENT:"instructions"::STRING,
    JSON_CONTENT:"name"::STRING,
    JSON_CONTENT:"photo"::STRING,
    JSON_CONTENT:"price"::FLOAT,
    JSON_CONTENT:"productid"::STRING
    FROM RAW_JSON_DATA;

   SELECT * FROM FLOWERS;